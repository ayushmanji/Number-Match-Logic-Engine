export function getLevelConfig(level: number): LevelConfig {
  if (LEVEL_CONFIGS[level]) {
    return LEVEL_CONFIGS[level];
  }
  
  const extraLevels = level - 15;
  const initialMatchDensity = Math.max(0.02, 0.05 - extraLevels * 0.002);
  const decoyRatio = Math.min(0.80, 0.70 + extraLevels * 0.01);
  const targetTimeSeconds = Math.max(30, 40 - Math.floor(extraLevels * 0.5));

  return {
    level,
    targetTimeSeconds,
    experienceGoal: `Level ${level} (Master Challenge): High friction, precise strategy required.`,
    targetAddRowsMin: 5,
    targetAddRowsMax: 6,
    initialMatchDensity,
    decoyRatio,
    isReliefLevel: false,
    winProbabilityTarget: Math.max(0.10, 0.35 - extraLevels * 0.02),
  };
}
